#!/usr/bin/env node
// Embeds a built agav-sandbox.exe into source/utils/windows-sandbox-bundle.ts.
// Usage: node scripts/embed-windows-sandbox-helper.mjs <helper.exe> <outputTs>
import { createHash } from "node:crypto";
import { lstatSync, mkdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { gzipSync } from "node:zlib";

const MAX_SIZE = 32 * 1024 * 1024;
const PROTOCOL = "agav-sandbox 1";

function validatePeX64(bytes) {
  const invalid = () => { throw new Error("Helper is not a 64-bit x64 PE executable."); };
  if (bytes.length < 64 || bytes.subarray(0, 2).toString() !== "MZ") invalid();
  const offset = bytes.readUInt32LE(60);
  if (offset < 64 || offset > bytes.length - 26 || bytes.readUInt32LE(offset) !== 0x00004550 ||
      bytes.readUInt16LE(offset + 4) !== 0x8664 || bytes.readUInt16LE(offset + 24) !== 0x20b) invalid();
}

try {
  const [helperPath, outputTs, ...extra] = process.argv.slice(2);
  if (!helperPath || !outputTs || extra.length) throw new Error("Usage: node scripts/embed-windows-sandbox-helper.mjs <helper.exe> <outputTs>");
  const info = lstatSync(helperPath);
  if (!info.isFile() || info.size <= 0 || info.size > MAX_SIZE) throw new Error("Helper must be a regular, nonempty file no larger than 32 MiB (not a symlink).");
  const bytes = readFileSync(helperPath);
  if (bytes.length !== info.size) throw new Error("Helper changed while reading.");
  validatePeX64(bytes);
  const bundle = {
    protocol: PROTOCOL,
    size: bytes.length,
    sha256: createHash("sha256").update(bytes).digest("hex"),
    gzipBase64: gzipSync(bytes, { level: 9 }).toString("base64"),
  };
  const content = `// Generated by scripts/embed-windows-sandbox-helper.mjs. Do not edit.
export interface BundledWindowsSandboxHelper {
  protocol: string;
  size: number;
  sha256: string;
  gzipBase64: string;
}
export const BUNDLED_WINDOWS_SANDBOX_HELPER: BundledWindowsSandboxHelper | null = ${JSON.stringify(bundle, null, 2)};
`;
  const output = resolve(outputTs);
  mkdirSync(dirname(output), { recursive: true });
  const staging = `${output}.${process.pid}.tmp`;
  writeFileSync(staging, content, { flag: "wx" });
  renameSync(staging, output);
  console.log(`Embedded Windows sandbox helper: ${bytes.length} bytes, SHA-256 ${bundle.sha256}`);
} catch (error) {
  console.error(`Cannot embed Windows sandbox helper: ${error.message}`);
  process.exitCode = 1;
}
