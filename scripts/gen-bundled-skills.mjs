// Regenerates source/skills/bundled-manifest.ts from source/skills/bundled/.
//
// The bundled skills are Markdown, so neither `tsc` nor `bun build --compile`
// carries them along on its own. Copying them next to the output only helps the
// Node build: in a compiled binary `import.meta.url` is `file:///$bunfs/root/…`,
// so any path the loader derives from it points into the virtual filesystem
// rather than at anything on disk. Inlining the files as strings is the one
// form that survives tsx, `node build/cli.js` and `./dist/agav` alike.
//
// Run via `pnpm gen:skills`; `build` and `build:binary` both do this first.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const bundledDir = join(root, "source", "skills", "bundled");
const outFile = join(root, "source", "skills", "bundled-manifest.ts");

const entries = readdirSync(bundledDir, { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort();

const records = [];
for (const name of entries) {
  let text;
  try {
    text = readFileSync(join(bundledDir, name, "SKILL.md"), "utf-8");
  } catch {
    console.warn(`gen:skills — skipping ${name}: no SKILL.md`);
    continue;
  }
  // Normalise line endings so the generated file is byte-identical whether it
  // was produced from a checkout that materialised the .md files with LF or,
  // on Windows with core.autocrlf, with CRLF.
  records.push(`  ${JSON.stringify(name)}: ${JSON.stringify(text.replace(/\r\n/g, "\n"))},`);
}

const out = `// GENERATED by scripts/gen-bundled-skills.mjs — do not edit by hand.
// Edit the SKILL.md files under source/skills/bundled/ and run \`pnpm gen:skills\`.

/** Directory name -> raw SKILL.md contents, inlined so binaries can read them. */
export const BUNDLED_SKILL_FILES: Record<string, string> = {
${records.join("\n")}
};
`;

writeFileSync(outFile, out);
console.log(`gen:skills — wrote ${records.length} skills to source/skills/bundled-manifest.ts`);
