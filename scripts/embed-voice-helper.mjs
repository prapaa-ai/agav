#!/usr/bin/env node
import { createHash } from "node:crypto";
import { constants } from "node:fs";
import { lstat, mkdir, mkdtemp, open, readFile, rename, rm } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const targets = new Set(["darwin-arm64", "darwin-x64", "linux-arm64", "linux-x64", "win32-x64"]);
const maxSize = 128 * 1024 * 1024;
let staging;

function validateHeader(bytes, target) {
  const invalid = () => { throw new Error(`Invalid executable magic or architecture for ${target} (expected native ELF, Mach-O or PE header).`); };
  if (target.startsWith("darwin-")) {
    // Thin, 64-bit little-endian Mach-O. Universal files must be thinned for the release target.
    if (bytes.length < 32 || bytes.readUInt32LE(0) !== 0xfeedfacf ||
        bytes.readUInt32LE(4) !== (target.endsWith("arm64") ? 0x0100000c : 0x01000007) ||
        bytes.readUInt32LE(12) !== 2) invalid();
  } else if (target.startsWith("linux-")) {
    if (bytes.length < 64 || bytes.subarray(0, 4).toString("hex") !== "7f454c46" ||
        bytes[4] !== 2 || bytes[5] !== 1 || bytes[6] !== 1 ||
        ![2, 3].includes(bytes.readUInt16LE(16)) ||
        bytes.readUInt16LE(18) !== (target.endsWith("arm64") ? 183 : 62)) invalid();
  } else {
    if (bytes.length < 64 || bytes.subarray(0, 2).toString() !== "MZ") invalid();
    const offset = bytes.readUInt32LE(60);
    if (offset < 64 || offset > bytes.length - 26 || bytes.readUInt32LE(offset) !== 0x00004550 ||
        bytes.readUInt16LE(offset + 4) !== 0x8664 || bytes.readUInt16LE(offset + 24) !== 0x20b) invalid();
  }
}

async function readHelper(helperPath, target) {
  const info = await lstat(helperPath);
  if (!info.isFile() || info.size <= 0 || info.size > maxSize) throw new Error("Helper must be a regular, nonempty file no larger than 128 MiB (not a symlink).");
  return readValidatedHelper(helperPath, target, info);
}

async function readValidatedHelper(helperPath, target, info) {
  const file = await open(helperPath, constants.O_RDONLY | (constants.O_NOFOLLOW ?? 0));
  let bytes;
  try {
    const opened = await file.stat();
    if (!opened.isFile() || opened.ino !== info.ino || opened.dev !== info.dev || opened.size !== info.size) throw new Error("Helper changed while opening.");
    bytes = Buffer.alloc(info.size);
    let offset = 0;
    while (offset < bytes.length) {
      const { bytesRead } = await file.read(bytes, offset, bytes.length - offset, null);
      if (!bytesRead) throw new Error("Helper truncated while reading.");
      offset += bytesRead;
    }
    const after = await file.stat();
    if (after.size !== info.size || after.mtimeMs !== info.mtimeMs || after.ctimeMs !== info.ctimeMs) throw new Error("Helper changed while reading.");
  } finally { await file.close(); }
  validateHeader(bytes, target);
  return bytes;
}

try {
  const [target, helperPath, outputTs, ...extra] = process.argv.slice(2);
  if (!targets.has(target) || !helperPath || !outputTs || extra.length) {
    throw new Error("Usage: node scripts/embed-voice-helper.mjs <darwin-arm64|darwin-x64|linux-arm64|linux-x64|win32-x64> <helperPath> <outputTs>; unknown targets are not supported.");
  }
  const bytes = await readHelper(helperPath, target);
  const licenses = {
    whisper: await readFile(join(root, "native/voice/LICENSE.whisper.cpp"), "utf8"),
    miniaudio: await readFile(join(root, "native/voice/LICENSE.miniaudio"), "utf8"),
  };
  if (!licenses.whisper.trim() || !licenses.miniaudio.trim()) throw new Error("Native voice licenses must not be empty.");
  const bundle = { target, size: bytes.length, sha256: createHash("sha256").update(bytes).digest("hex"), gzipBase64: gzipSync(bytes, { level: 9 }).toString("base64"), licenses };
  if (target.endsWith("-x64")) {
    let sibling;
    try { sibling = await readHelper(`${helperPath}.avx2`, target); }
    catch (error) { if (error.code !== "ENOENT") throw error; }
    if (sibling) bundle.avx2 = { target, size: sibling.length, sha256: createHash("sha256").update(sibling).digest("hex"), gzipBase64: gzipSync(sibling, { level: 9 }).toString("base64"), licenses };
  }
  const content = `// Generated by scripts/embed-voice-helper.mjs. Do not edit.\nexport interface BundledVoiceRuntime {\n  target: string;\n  size: number;\n  sha256: string;\n  gzipBase64: string;\n  licenses: { whisper: string; miniaudio: string };\n  avx2?: Omit<BundledVoiceRuntime, "avx2">;\n}\nexport const BUNDLED_VOICE_RUNTIME: BundledVoiceRuntime | null = ${JSON.stringify(bundle, null, 2)};\n`;
  const output = resolve(outputTs);
  await mkdir(dirname(output), { recursive: true });
  staging = await mkdtemp(join(dirname(output), ".embed-voice-helper-"));
  const temporary = join(staging, "bundled-runtime.ts");
  const generated = await open(temporary, "wx", 0o644);
  try { await generated.writeFile(content); await generated.sync(); }
  finally { await generated.close(); }
  await rename(temporary, output);
  console.log(`Embedded voice helper ${target}: ${bytes.length} bytes, SHA-256 ${bundle.sha256}`);
} catch (error) {
  console.error(`Cannot embed voice helper: ${error.message}`);
  process.exitCode = 1;
} finally {
  if (staging) await rm(staging, { recursive: true, force: true });
}
